"""Build sessions/<name>/run-of-show.md (and docs/sessions/<name>.md if public) from session.yml.

`--inline` instead rewrites sessions/<name>/slides/deck.html so images and fonts are data URIs, which
makes the file work from any URL (the docs site serves it in an iframe).
"""
import base64
import mimetypes
import re
import sys
from datetime import datetime, timedelta
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent


def module_info(name: str) -> dict:
    readme = (ROOT / "modules" / name / "README.md").read_text()
    title = re.search(r"^# (.+)$", readme, re.MULTILINE).group(1)
    leave = re.search(r"^## Goal\n\n(.+?)\.?\n", readme, re.MULTILINE)
    return {"title": title, "command": f"make module M={name}", "leave_with": leave.group(1) if leave else ""}


def run_of_show(folder: Path, docs: bool = False, day: int | None = None) -> str:
    cfg = yaml.safe_load((folder / "session.yml").read_text())
    if day is not None:  # multi-day session: `days:` entries override date/start/blocks and may add a name
        cfg = {**cfg, **cfg["days"][day]}
        cfg["title"] = f"{cfg['title']} · {cfg['name']}"
    start = datetime.strptime(str(cfg["start"]), "%H:%M")  # noqa: DTZ007 wall-clock times, no timezone
    clock = timedelta()
    rows = []
    for b in cfg["blocks"]:
        info = module_info(b["module"]) if "module" in b else {}
        info.update({k: v for k, v in b.items() if k in ("title", "command", "leave_with")})
        link = info["title"]
        if "module" in b:
            href = f"../modules/{b['module']}.md" if docs else f"../../modules/{b['module']}/README.md"
            link = f"[{link}]({href})"
        cmd = f"`{info['command']}`" if info.get("command") else ""
        at = "" if docs else f"{(start + clock).strftime('%H:%M')} | "  # the public page frames a session in minutes, no clock
        rows.append(f"| {at}{b['minutes']} | {link} | {cmd} | {info.get('leave_with', '')} |")
        clock += timedelta(minutes=b["minutes"])
    head = "" if docs else f"# {cfg['title']} · {cfg['date']}\n\n<!-- generated by scripts/build_session.py from session.yml; edit that instead -->\n\n"
    minutes = int(clock.total_seconds() // 60)
    if docs:
        table = "| Min | Block | You run | You leave with |\n|---|---|---|---|\n" + "\n".join(rows)
        return f"{head}{table}\n\nTotal: {minutes} min.\n"
    table = "| Clock | Min | Block | You run | You leave with |\n|---|---|---|---|---|\n" + "\n".join(rows)
    return f"{head}{table}\n\nEnds {(start + clock).strftime('%H:%M')} ({minutes} min).\n"


SLIDES = (  # iframe src is raw HTML, relative to the rendered /sessions/<name>/; md links resolve from docs/sessions/
    '<iframe src="slides/deck.html" title="Slides" style="width:100%;aspect-ratio:16/9;border:0" allowfullscreen></iframe>\n\n'
    "[Open the slides full screen]({name}/slides/deck.html){{ .md-button }}\n"
)


def docs_page(folder: Path) -> str:
    cfg = yaml.safe_load((folder / "session.yml").read_text())
    part = folder / "participant.md"
    text = part.read_text() if part.exists() else f"# {cfg['title']} · {cfg['date']}\n\n<!-- run-of-show -->\n\n<!-- slides -->\n"
    return text.replace("<!-- run-of-show -->", run_of_show(folder, docs=True)).replace("<!-- slides -->", SLIDES.format(name=folder.name))


def inline_assets(folder: Path) -> None:
    deck = folder / "slides" / "deck.html"

    def data_uri(path: Path) -> str:
        return f"data:{mimetypes.guess_type(path.name)[0]};base64,{base64.b64encode(path.read_bytes()).decode()}"

    html = deck.read_text()
    # theme fonts are relative to slides/ (where orq-theme.css lives), images to the deck itself
    html = re.sub(r'url\("(\.\./[^"]+)"\)', lambda m: f'url("{data_uri((ROOT / "slides" / m[1]).resolve())}")', html)
    html = re.sub(r'src="(\.[^"]+)"', lambda m: f'src="{data_uri((deck.parent / m[1]).resolve())}"', html)
    deck.write_text(html)


def main(name: str, inline: bool = False) -> None:
    folder = ROOT / "sessions" / name
    if inline:
        return inline_assets(folder)
    cfg = yaml.safe_load((folder / "session.yml").read_text())
    for i in range(len(cfg.get("days", []))):  # ponytail: multi-day sessions are private, no docs page
        (folder / f"run-of-show-day{i + 1}.md").write_text(run_of_show(folder, day=i))
    if "days" not in cfg:
        (folder / "run-of-show.md").write_text(run_of_show(folder))
    page = ROOT / "docs" / "sessions" / f"{name}.md"
    if yaml.safe_load((folder / "session.yml").read_text()).get("public"):
        page.parent.mkdir(exist_ok=True)
        page.write_text(docs_page(folder))
    elif page.exists():
        page.unlink()


if __name__ == "__main__":
    main(sys.argv[1], "--inline" in sys.argv)
